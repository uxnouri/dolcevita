// @ts-check
import { defineConfig } from "astro/config";
import tailwindcss from "@tailwindcss/vite";
import sitemap from "@astrojs/sitemap";
import { writeFile } from "node:fs/promises";

/**
 * Everything Astro writes to /_astro/ has a content hash in its file name (a new version gets a
 * new name), so browsers may keep it for a year. Astro owns that folder, so the .htaccess saying
 * so is written after the build rather than kept in public/.
 */
/** @returns {import("astro").AstroIntegration} */
function hashedAssetCache() {
  return {
    name: "hashed-asset-cache",
    hooks: {
      "astro:build:done": async ({ dir }) => {
        await writeFile(
          new URL("_astro/.htaccess", dir),
          [
            "# Content-hashed build files: safe to cache for a year (generated by astro.config.mjs).",
            "<IfModule mod_headers.c>",
            '  Header set Cache-Control "public, max-age=31536000, immutable"',
            "</IfModule>",
            "<IfModule mod_expires.c>",
            "  ExpiresActive On",
            '  ExpiresDefault "access plus 1 year"',
            "</IfModule>",
            "",
          ].join("\n"),
        );
      },
    },
  };
}

// https://astro.build/config
export default defineConfig({
  site: "https://dolcevitadesign.ma",
  trailingSlash: "always",
  build: {
    format: "directory",
    inlineStylesheets: "auto", // one shared, cacheable CSS file across all pages
  },
  i18n: {
    defaultLocale: "fr",
    locales: ["fr", "en"],
    routing: { prefixDefaultLocale: false },
  },
  prefetch: { prefetchAll: true, defaultStrategy: "hover" },
  image: {
    responsiveStyles: true,
    // Encoder settings for every image Astro generates (sharp). Tuned for photos of furniture:
    // visually indistinguishable from the originals at a fraction of the weight.
    service: {
      entrypoint: "astro/assets/services/sharp",
      config: {
        avif: { quality: 55, effort: 4 },
        webp: { quality: 75, effort: 5, smartSubsample: true },
        jpeg: { quality: 72, mozjpeg: true },
      },
    },
  },
  integrations: [sitemap(), hashedAssetCache()],
  vite: { plugins: [tailwindcss()] },
});
